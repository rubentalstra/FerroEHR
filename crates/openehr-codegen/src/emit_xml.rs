//! XML emitter (ADR-005): emits `impl ToXml` + `impl FromXml` for the generated
//! RM/BASE spec types, into `openehr-its/src/xml/generated/`.
//!
//! The Rust facts (field idents, exact field types, enum variants, generics)
//! come from [`Model::xml_types`]; the wire shape (element order, attribute-vs-
//! element split for serialization, `xsi:type` slots) comes from the
//! [`XsdModel`]. Fields are matched to XSD elements/attributes by openEHR
//! property name; a struct absent from the XSD serializes in BMM field order
//! with no attributes. Deserialization dispatches child elements by name (order
//! -independent) and polymorphic slots by `xsi:type`.

use crate::bmm::BmmSchema;
use crate::emit::{Model, XmlField, XmlType};
use crate::xsd::XsdModel;
use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write as _;

/// One spec schema paired with the crate prelude its types are re-exported from.
pub struct XmlSchema<'a> {
    pub model: &'a Model,
    pub schema: &'a BmmSchema,
    /// e.g. `openehr_rm::prelude` / `openehr_base::prelude`.
    pub prelude: &'a str,
}

/// Emit the whole generated impl file. `unmatched` receives `(type, element)`
/// pairs the XSD declared for serialization but BMM has no field for (skipped).
///
/// # Errors
/// Fails codegen (F-05-01 guard) if any emitted LOCATABLE subtype would serialize
/// `archetype_node_id` as a child element rather than the required XML attribute
/// (i.e. its XSD closure is missing, so it falls back to attribute-less BMM order).
pub fn emit_file(
    schemas: &[XmlSchema<'_>],
    xsd: &XsdModel,
    unmatched: &mut Vec<(String, String)>,
) -> Result<String, String> {
    let mut b = String::new();
    b.push_str(
        "// @generated by openehr-codegen (emit-xml) — DO NOT EDIT.\n\
         // Canonical-XML `ToXml`/`FromXml` impls for the RM/BASE spec types.\n\n\
         #![allow(clippy::all, clippy::pedantic, clippy::nursery, unused_variables, unused_mut)]\n\
         #[allow(unused_imports)]\n\
         use crate::xml::runtime::{ToXml, FromXml, XmlEvent, XmlError};\n\n",
    );
    let mut locatable_violations: Vec<String> = Vec::new();
    let mut bmm_only_violations: Vec<String> = Vec::new();
    let mut appended: Vec<String> = Vec::new();
    for s in schemas {
        for ty in s.model.xml_types(s.schema) {
            check_locatable_attr(&ty, xsd, &mut locatable_violations);
            check_bmm_field_coverage(&ty, xsd, &mut bmm_only_violations);
            if let XmlType::Struct { spec, fields, .. } = &ty {
                for f in bmm_only_fields(spec, fields, xsd) {
                    appended.push(format!("{spec}.{}", f.wire_name));
                }
            }
            emit_to_xml(&mut b, &ty, s.prelude, xsd, unmatched);
            emit_from_xml(&mut b, &ty, s.prelude, xsd);
        }
    }
    if !appended.is_empty() {
        eprintln!(
            "emit-xml (F-05-02): {} allowlisted BMM-only field(s) appended as trailing \
             canonical-XML elements (RM 1.2.0 / BASE 1.3.0 vs vendored ITS-XML skew): {}",
            appended.len(),
            appended.join(", ")
        );
    }
    if !locatable_violations.is_empty() {
        return Err(format!(
            "emit-xml guard (F-05-01): {} LOCATABLE subtype(s) have no XSD closure, so \
             `archetype_node_id` would serialize as a child element instead of the required \
             XML attribute: {}. Extend the XSD input (crates/openehr-codegen/src/xsd.rs) so \
             these types reach `LOCATABLE`.",
            locatable_violations.len(),
            locatable_violations.join(", ")
        ));
    }
    if !bmm_only_violations.is_empty() {
        return Err(format!(
            "emit-xml guard (F-05-02): {} BMM field(s) of XSD-covered type(s) have no matching \
             XSD element/attribute, so the XSD-driven `ToXml` would silently drop them while the \
             BMM-driven `FromXml` still reads them (an undetectable JSON/XML divergence). Either \
             extend the driving XSD input (crates/openehr-codegen/src/xsd.rs) so the field gets a \
             deterministic slot, or add it to `XML_BMM_ONLY_ALLOWLIST` in emit_xml.rs (with a \
             spec-delta citation) to have it appended as a trailing canonical-XML element. \
             Fields: {}.",
            bmm_only_violations.len(),
            bmm_only_violations.join(", ")
        ));
    }
    Ok(b)
}

/// F-05-01 guard: any emitted struct carrying an `archetype_node_id` field (per
/// the BMM, a LOCATABLE subtype) must have that field classified as an XML
/// **attribute** by the driving XSD. `LOCATABLE` declares `archetype_node_id`
/// `use="required"` (an attribute); a type whose XSD closure is missing falls
/// back to attribute-less BMM field order and would emit it as a child element —
/// invalid canonical XML. Record the violation so codegen fails loudly.
fn check_locatable_attr(ty: &XmlType, xsd: &XsdModel, violations: &mut Vec<String>) {
    if let XmlType::Struct { spec, fields, .. } = ty {
        let has_archetype_node_id = fields.iter().any(|f| f.wire_name == "archetype_node_id");
        if has_archetype_node_id && !attr_names(spec, xsd).contains("archetype_node_id") {
            violations.push(spec.clone());
        }
    }
}

/// `(impl<…: Bound> , <…>)` — the impl-generics header and the type-args suffix.
fn generic_header(generics: &[String], bound: &str) -> (String, String) {
    if generics.is_empty() {
        (String::new(), String::new())
    } else {
        let bounded = generics
            .iter()
            .map(|g| format!("{g}: {bound}"))
            .collect::<Vec<_>>()
            .join(", ");
        (format!("<{bounded}>"), format!("<{}>", generics.join(", ")))
    }
}

/// A local accumulator variable name for a field. Strips the `r#` raw-identifier
/// prefix (`r#type` → `__type`) since `__r#type` is not a valid identifier.
fn acc_var(rust_name: &str) -> String {
    format!("__{}", rust_name.trim_start_matches("r#"))
}

/// XSD attribute names for a type (empty if the type is not in the XSD).
fn attr_names(spec: &str, xsd: &XsdModel) -> BTreeSet<String> {
    if xsd.types.contains_key(spec) {
        xsd.flattened(spec)
            .0
            .iter()
            .map(|a| a.name.clone())
            .collect()
    } else {
        BTreeSet::new()
    }
}

