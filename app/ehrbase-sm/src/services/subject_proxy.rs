/// The retrieval method of a [`DataFrame`]. The SM types this
/// `SYSTEM_CALL [0..1]` (openEHR PROC `task_planning.html#_system_call_class`),
/// with the `QUERY_CALL` / `API_CALL` descendants shown in the master10 YAML
/// examples (§Specifying a Binding).
///
/// PORT NOTE: `SYSTEM_CALL` and its PROC descendants are **not** vendored or
/// generated in this workspace (the PROC/task-planning spec is out of scope), so
/// the method is modelled as the closed set the frame executors actually
/// dispatch on. Only [`FrameMethod::Aql`] is realized; the FHIR / `HL7v2` variants
/// are typed seams (`get_frame` rejects them `NotImplemented`).
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(tag = "_type")]
pub enum FrameMethod {
    /// openEHR `QUERY_CALL` (`call_name: aql_query`): AQL executed through the
    /// Query service, producing a `RESULT_SET` ([`FramePayload::Openehr`]).
    #[serde(rename = "QUERY_CALL")]
    Aql {
        /// The AQL query text (may reference `$subject_id`, bound by the
        /// executor to the `get_frame` subject).
        query_text: String,
    },
    /// HL7 FHIR `API_CALL` seam — carried verbatim, executed nowhere yet.
    #[serde(rename = "FHIR_API_CALL")]
    Fhir {
        /// Target system identifier.
        #[serde(default, skip_serializing_if = "Option::is_none")]
        system_id: Option<String>,
        /// Named API call (e.g. `fhir_get`).
        #[serde(default, skip_serializing_if = "Option::is_none")]
        call_name: Option<String>,
        /// Query/URL text for the FHIR request.
        #[serde(default, skip_serializing_if = "Option::is_none")]
        query_text: Option<String>,
    },
    /// `HL7v2` seam — carried verbatim, executed nowhere yet.
    #[serde(rename = "HL7v2_CALL")]
    Hl7v2 {
        /// Target system identifier.
        #[serde(default, skip_serializing_if = "Option::is_none")]
        system_id: Option<String>,
        /// Named call.
        #[serde(default, skip_serializing_if = "Option::is_none")]
        call_name: Option<String>,
    },
}

/// `DATA_FRAME` — "Data retrieval frame, consisting of primary and fallback
/// retrieval methods … and most recent result" (`data_frame.adoc`).
///
/// PORT NOTE: the runtime "most recent result" is not persisted (master10
/// §Persistence); this configuration type carries `id`, `model_type`, and the
/// primary/fallback methods only.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct DataFrame {
    /// `id [1]` — the frame identifier (e.g. `openEHR::vital_signs`), referenced
    /// by [`SubjectVariable::frame_id`].
    pub id: String,
    /// `model_type [1]` — name of the underlying model/type system, e.g.
    /// `"openehr"`, `"hl7v2"`, `"hl7-fhir"` ("Currently not standardised").
    pub model_type: String,
    /// `primary_method: SYSTEM_CALL [0..1]` — the method used to perform the
    /// retrieval.
    pub primary_method: FrameMethod,
    /// `fallback_method: SYSTEM_CALL [0..1]` — alternative method if the primary
    /// retrieve fails.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub fallback_method: Option<FrameMethod>,
}

