// ─── VARIABLE_VALUE hierarchy (`variable_value*.adoc`) ────────────────────────

/// `VARIABLE_VALUE` — "Abstract parent of variable value structures"
/// (`variable_value.adoc`). Its three concrete descendants form a closed subtype
/// set, so this is an idiomatic Rust enum (the codegen closed-subtype rule) rather
/// than a trait; the payloads are `Any`, carried as canonical JSON [`Value`]s.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(tag = "_type")]
pub enum VariableValue {
    /// `VARIABLE_VALUE_SINGLE` — "Atomic Variable value" (`value: Any [0..1]`,
    /// `variable_value_single.adoc`).
    #[serde(rename = "VARIABLE_VALUE_SINGLE")]
    Single {
        /// The single value, from the source frame's latest sample.
        value: Option<Value>,
    },
    /// `VARIABLE_VALUE_LIST` — "Variable value in the form of a list"
    /// (`value: List<Any> [0..1]`, `variable_value_list.adoc`).
    #[serde(rename = "VARIABLE_VALUE_LIST")]
    List {
        /// The list of values, from the source frame's latest sample.
        value: Vec<Value>,
    },
    /// `VARIABLE_VALUE_TIME_SERIES` — "Variable value in the form of a
    /// time-series" (`value: Hash<Iso8601_date_time, Any> [0..1]`,
    /// `variable_value_time_series.adoc`).
    #[serde(rename = "VARIABLE_VALUE_TIME_SERIES")]
    TimeSeries {
        /// The time-keyed values (ISO-8601 date-time → `Any`).
        value: BTreeMap<String, Value>,
    },
}

// ─── SAMPLE hierarchy (`sample.adoc`, `data_frame_sample.adoc`, …) ────────────

/// `SAMPLE<T>` — "One retrieval (sample) of a data 'block', generated by
/// invocation of some retrieval method … encompasses retrieval (attempt)
/// time-stamp, availability status, and result, if available" (`sample.adoc`).
///
/// Generic over the payload `T`, exactly as the spec's `SAMPLE<T>`:
/// [`DataFrameSample`] is `Sample<FramePayload>` and [`VariableSample`] is
/// `Sample<VariableValue>`.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct Sample<T> {
    /// `retrieve_time [1]` — time the retrieve attempt was made (ISO-8601).
    pub retrieve_time: String,
    /// `effective_time [0..1]` — real-world time the data pertains to, if
    /// available (compared against [`SubjectVariable::currency`] for freshness).
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub effective_time: Option<String>,
    /// `is_unavailable [1]` — true if no data was available for this attempt.
    pub is_unavailable: bool,
    /// `unavailable_reason [0..1]` — reason for absent data, if any.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub unavailable_reason: Option<String>,
    /// `result: T [0..1]` — result of the retrieve call, if available.
    #[serde(default = "Option::default", skip_serializing_if = "Option::is_none")]
    pub result: Option<T>,
}

impl<T> Sample<T> {
    /// An available sample carrying `result`, stamped `retrieve_time = now`.
    #[must_use]
    pub fn available(result: T) -> Self {
        Self {
            retrieve_time: now_iso(),
            effective_time: None,
            is_unavailable: false,
            unavailable_reason: None,
            result: Some(result),
        }
    }

    /// An unavailable sample (`is_unavailable = true`) with a reason.
    #[must_use]
    pub fn unavailable(reason: impl Into<String>) -> Self {
        Self {
            retrieve_time: now_iso(),
            effective_time: None,
            is_unavailable: true,
            unavailable_reason: Some(reason.into()),
            result: None,
        }
    }
}

/// The payload of a [`DataFrameSample`]: the closed set of the three concrete
/// `DATA_FRAME_SAMPLE` descendants the spec defines
/// (`openehr_sample.adoc` / `hl7v2_sample.adoc` / `hl7_fhir_sample.adoc`).
/// Modelling the descendants as an enum variant on the payload is the codegen's
/// closed-subtype treatment.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(tag = "_type")]
pub enum FramePayload {
    /// `OPENEHR_SAMPLE` — "openEHR sample whose result is in the form of a
    /// `RESULT_SET` structure" (`openehr_sample.adoc`). Carries the ITS-REST
    /// 1.0.3 `RESULT_SET` canonical JSON the Query service returned.
    #[serde(rename = "OPENEHR_SAMPLE")]
    Openehr {
        /// The `RESULT_SET` (canonical JSON).
        result_set: Value,
    },
    /// `HL7v2_SAMPLE` — "Container for `HL7v2` message based data frame results"
    /// (`hl7v2_sample.adoc`). Stubbed seam (never produced yet — see
    /// [`DataBinding::get_frame`]).
    #[serde(rename = "HL7v2_SAMPLE")]
    Hl7v2 {
        /// The raw `HL7v2` message text.
        message: String,
    },
    /// `HL7_FHIR_SAMPLE` — "Container for HL7 FHIR based data frame results"
    /// (`hl7_fhir_sample.adoc`). Stubbed seam (never produced yet).
    #[serde(rename = "HL7_FHIR_SAMPLE")]
    Hl7Fhir {
        /// The FHIR resource (canonical JSON).
        resource: Value,
    },
}

/// `DATA_FRAME_SAMPLE<T>` — "Abstract class with methods for extracting single
/// variable values from data frames" (`data_frame_sample.adoc`); a `SAMPLE`
/// whose payload is a back-end retrieval result ([`FramePayload`]).
pub type DataFrameSample = Sample<FramePayload>;

/// `VARIABLE_SAMPLE` — "Sample whose result is in the form of a `VARIABLE_VALUE`
/// (descendant) structure" (`variable_sample.adoc`).
pub type VariableSample = Sample<VariableValue>;

// ─── SUBJECT_VARIABLE (`subject_variable.adoc`) ───────────────────────────────

/// `SUBJECT_VARIABLE` — "A single subject variable whose data may take various
/// forms, including atomic, list and time series" (`subject_variable.adoc`).
///
/// PORT NOTE (dropped runtime attributes). The spec's `history:
/// List<VARIABLE_SAMPLE> [0..1]` and `last_frame: DATA_FRAME_SAMPLE [0..1]` are
/// *runtime* sample state, not configuration; master10 §Persistence persists
/// only "the configuration contents (i.e. not data frame or variable results)".
/// This definition-time type therefore omits them — sample history / last-frame
/// caching (the `sp_sample` store + currency-based freshness of design 08 §4.4)
/// is deferred, and [`get_variable`](SubjectProxyService::get_variable)
/// re-executes the bound frame each call (always "most recent available", which
/// `currency = Void` explicitly allows).
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct SubjectVariable {
    /// `namespace [0..1]` — optional namespace qualifying `name` (e.g.
    /// `cha2ds2vasc`); unset ⇒ the variable is in the 'global' namespace.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub namespace: Option<String>,
    /// `name [1]` — canonical name by which this item is known in the service
    /// (e.g. `date_of_birth`).
    pub name: String,
    /// `type_name [1]` — formal type name from the defining model.
    pub type_name: String,
    /// `currency: Iso8601_duration [0..1]` — required currency; unset ⇒ most
    /// recent available is valid.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub currency: Option<String>,
    /// `ask_user: Boolean [0..1]` — if true, the service should attempt to
    /// obtain the item from a live user (unsupported here; see the type doc).
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub ask_user: Option<bool>,
    /// `is_manual: Boolean [1]` — true if obtained by manual notification.
    pub is_manual: bool,
    /// `frame_id [1]` — identifier of the retrieve frame from which to extract
    /// this variable.
    pub frame_id: String,
    /// `frame_path [1]` — path within the `last_frame` result at which the
    /// value sits (see [`SubjectProxyService::get_variable`] for the `RESULT_SET`
    /// selector semantics we adopt).
    pub frame_path: String,
}

impl SubjectVariable {
    /// `canonical_name (): String` — "Return canonical name, formed from
    /// `namespace` (if present) and `name` … `namespace::name` … or just
    /// `name`" (`subject_variable.adoc`).
    /// Subject-variable naming validity (SM master10 §Subject Variable
    /// Naming): a canonical name "may not include whitespace or any
    /// unprintable character". Checked over both `name` and `namespace`
    /// (the canonical name is formed from them); the name must be non-empty.
    #[must_use]
    pub fn name_valid(&self) -> bool {
        fn part_ok(s: &str) -> bool {
            !s.is_empty() && s.chars().all(|c| !c.is_whitespace() && !c.is_control())
        }
        part_ok(&self.name) && self.namespace.as_deref().is_none_or(part_ok)
    }

    #[must_use]
    pub fn canonical_name(&self) -> String {
        match &self.namespace {
            Some(ns) if !ns.is_empty() => format!("{ns}::{}", self.name),
            _ => self.name.clone(),
        }
    }

    /// `is_global (): Boolean` with `__Post_result__: Result = (namespace =
    /// Void)` — "True if `namespace` is set". PORT NOTE: the prose ("True if
    /// namespace is set") contradicts the post-condition; per the design digest
    /// (§2.2) the post-condition is the consistent reading — *global* means
    /// **no** namespace.
    #[must_use]
    pub fn is_global(&self) -> bool {
        self.namespace.as_ref().is_none_or(String::is_empty)
    }
}

