//! `emit-validate`: emit the **RM class-invariant cores** into `openehr-rm`
//! (`src/validate/generated.rs`), the single source both the typed `Validate`
//! impls (`*_impl.rs`) and the allocation-free fast path (`validate::fast`)
//! call for every mechanically-shaped RM class invariant.
//!
//! The cores' bodies are fixed spec logic (one `pub(crate) fn <name>_core` per
//! invariant group, each preserving the archie-style violation message verbatim
//! — see [`CORES`]); what the emitter derives from the vendored inputs is (a)
//! the `PROPORTION_KIND` codes, read from the RM BMM enumeration, and (b) the
//! **pending-adjudication register** — every RM class invariant the
//! assertion-dialect classifier ([`crate::analyze::invariants`]) marks
//! `runtime-hook-missing`, rendered as a doc note so the generated file honestly
//! accounts for the invariants no core yet realizes (nothing silently dropped).
//!
//! One generated file under `openehr-rm/src/validate/`; the hand-written
//! `validate.rs` declares `pub(crate) mod generated;` and keeps the runtime
//! helpers the cores call (`invariant_failed`, the ISO-8601 validators, the
//! dialect predicates).

use crate::analyze::Model;
use crate::analyze::invariants::{Bucket, classify};
use crate::load::bmm::{BmmEnumValue, BmmSchema};
use crate::render::emit::GenFile;

/// Emit the `validate/generated.rs` file for `openehr-rm` from the merged
/// BASE + RM model (for the `PROPORTION_KIND` codes) and the RM own schema (for
/// the class-invariant classification register).
#[must_use]
pub(crate) fn emit_files(model: &Model, own_schema: &BmmSchema) -> Vec<GenFile> {
    let mut body = String::new();
    body.push_str("// @generated by openehr-codegen (emit-validate) — DO NOT EDIT.\n");
    body.push_str(MODULE_DOC_INTRO);
    body.push_str(&pending_register(own_schema));
    body.push_str(MODULE_DOC_EXCLUDED);
    body.push('\n');
    body.push_str(IMPORTS);
    body.push('\n');
    body.push_str(&proportion_kind_consts(model));
    body.push('\n');
    body.push_str(CORES);
    vec![GenFile {
        path: "validate/generated.rs".to_string(),
        body,
    }]
}

/// The `PROPORTION_KIND` code constants, read from the RM BMM enumeration
/// (`pk_ratio = 0 … pk_integer_fraction = 4`). The `DV_PROPORTION` core compares
/// `kind` against the named codes rather than magic numbers.
fn proportion_kind_consts(model: &Model) -> String {
    let mut b = String::from(
        "// `PROPORTION_KIND` codes, generated from the RM BMM enumeration\n\
         // (`docs/specs/openehr/RM/docs/UML/classes/org.openehr.rm.data_types.proportion_kind.adoc`).\n",
    );
    let Some(class) = model.get("PROPORTION_KIND") else {
        return b;
    };
    let Some(e) = &class.enumeration else {
        return b;
    };
    for (i, name) in e.item_names.iter().enumerate() {
        let value = match e.item_values.as_ref().and_then(|v| v.get(i)) {
            Some(BmmEnumValue::Int(v)) => *v,
            _ => i64::try_from(i).unwrap_or_default(),
        };
        // `pk_ratio` (code 0) is the default kind with no dedicated invariant.
        if name == "pk_ratio" {
            b.push_str(
                "#[allow(dead_code)] // ratio (code 0) has no dedicated proportion invariant\n",
            );
        }
        b.push_str(&format!(
            "const {}: i32 = {value};\n",
            name.to_ascii_uppercase()
        ));
    }
    b
}

/// The pending-adjudication register: every RM class invariant the
/// assertion-dialect classifier marks `runtime-hook-missing`, one doc line each,
/// sorted `(class, name)`. Keeps the generated file honest — it names every
/// invariant no core realizes yet and why (the missing runtime hook).
fn pending_register(own_schema: &BmmSchema) -> String {
    let mut hooks: Vec<(String, String, &'static str)> = Vec::new();
    for (class, def) in &own_schema.classes {
        for (name, expr) in &def.invariants {
            if let Bucket::RuntimeHookMissing(reason) = classify(expr) {
                hooks.push((class.clone(), name.clone(), reason));
            }
        }
    }
    hooks.sort();
    let mut b = String::from(
        "//!\n\
         //! # Pending adjudication (runtime-hook-missing)\n\
         //!\n\
         //! These BMM class invariants are structurally within the dialect but each\n\
         //! needs a runtime hook the core layer cannot yet call (the openEHR\n\
         //! terminology service, a code-set, the demographic repository, or the\n\
         //! versioned-object aggregate model). No core realizes them here; they are\n\
         //! named so nothing is silently dropped:\n\
         //!\n",
    );
    for (class, name, reason) in &hooks {
        b.push_str(&format!("//! - `{class}.{name}` — {reason}.\n"));
    }
    b
}

