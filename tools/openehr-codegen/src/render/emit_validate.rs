/// DV_QUANTIFIED `Magnitude_status_valid`: if present, `magnitude_status` must
/// be one of `= < > <= >= ~`.
pub(crate) fn magnitude_status_core(
    ty: &str,
    magnitude_status: Option<&str>,
    out: &mut Vec<InvariantViolation>,
) {
    if let Some(s) = magnitude_status
        && !valid_magnitude_status(s)
    {
        out.push(invariant_failed("Magnitude_status_valid", ty));
    }
}

/// The DV_AMOUNT invariants (`Accuracy_is_percent_validity`, `Accuracy_validity`)
/// plus the inherited DV_QUANTIFIED `Magnitude_status_valid`. Shared by every
/// concrete DV_AMOUNT descendant (DV_QUANTITY, DV_COUNT, DV_DURATION,
/// DV_PROPORTION).
#[allow(clippy::float_cmp)] // exact accuracy == 0 test, mirrors archie's `accuracy == 0.0`
pub(crate) fn dv_amount_core(
    ty: &str,
    accuracy: Option<f64>,
    accuracy_is_percent: Option<bool>,
    magnitude_status: Option<&str>,
    out: &mut Vec<InvariantViolation>,
) {
    // Accuracy_is_percent_validity: accuracy = 0 implies not recorded as percent.
    if accuracy == Some(0.0) && accuracy_is_percent == Some(true) {
        out.push(invariant_failed("Accuracy_is_percent_validity", ty));
    }
    // Accuracy_validity: recorded as percent implies 0 <= accuracy <= 100.
    if accuracy_is_percent == Some(true)
        && let Some(a) = accuracy
        && !valid_percentage(a)
    {
        out.push(invariant_failed("Accuracy_validity", ty));
    }
    magnitude_status_core(ty, magnitude_status, out);
}

/// The temporal `Value_valid` invariant: the string value must be a
/// well-formed ISO-8601 date/time/date-time/duration (caller supplies the
/// verdict via the ISO-8601 validators).
pub(crate) fn temporal_value_core(ty: &str, valid: bool, out: &mut Vec<InvariantViolation>) {
    if !valid {
        out.push(invariant_failed("Value_valid", ty));
    }
}

/// The DV_PROPORTION own invariants. The inherited DV_AMOUNT / DV_ORDERED
/// invariants are pushed by the callers.
// openEHR/archie compare denominator against 0/1/100 by exact value
// (`denominator.equals(0d)` etc.), so exact float comparison is intended.
#[allow(clippy::float_cmp)]
pub(crate) fn dv_proportion_core(
    numerator: f64,
    denominator: f64,
    kind: i32,
    precision: Option<i32>,
    out: &mut Vec<InvariantViolation>,
) {
    let integral = is_integral(numerator) && is_integral(denominator);

    // Type_validity: type in 0..=4.
    if !valid_proportion_kind(kind) {
        out.push(InvariantViolation::here(
            "Invariant Type_validity failed on type DV_PROPORTION",
        ));
    }
    // Valid_denominator: denominator != 0.
    if denominator == 0.0 {
        out.push(InvariantViolation::here(
            "Invariant Valid_denominator failed on type DV_PROPORTION",
        ));
    }
    // Precision_validity: precision 0 implies integral numerator & denominator.
    if precision == Some(0) && !integral {
        out.push(InvariantViolation::here(
            "Invariant Precision_validity failed on type DV_PROPORTION",
        ));
    }
    // Fraction_validity: fraction / integer_fraction kinds are integral.
    if (kind == PK_FRACTION || kind == PK_INTEGER_FRACTION) && !integral {
        out.push(InvariantViolation::here(
            "Invariant Fraction_validity failed on type DV_PROPORTION",
        ));
    }
    // Unitary_validity: unitary kind has denominator 1.
    if kind == PK_UNITARY && denominator != 1.0 {
        out.push(InvariantViolation::here(
            "Invariant Unitary_validity failed on type DV_PROPORTION",
        ));
    }
    // Percent_validity: percent kind has denominator 100.
    if kind == PK_PERCENT && denominator != 100.0 {
        out.push(InvariantViolation::here(
            "Invariant Percent_validity failed on type DV_PROPORTION",
        ));
    }
}

