/// CODE_PHRASE `Code_string_valid`: the code string must be non-empty.
pub(crate) fn code_phrase_core(code_string: &str, out: &mut Vec<InvariantViolation>) {
    if code_string.is_empty() {
        out.push(InvariantViolation::here(
            "Invariant Code_string_valid failed on type CODE_PHRASE",
        ));
    }
}

/// DV_TEXT / DV_CODED_TEXT `Valid_value` (non-empty rubric) and
/// `Formatting_valid` (present ⇒ non-empty). `ty` is `DV_TEXT` or
/// `DV_CODED_TEXT` (which inherits both).
pub(crate) fn dv_text_core(
    ty: &str,
    value: &str,
    formatting: Option<&str>,
    out: &mut Vec<InvariantViolation>,
) {
    if value.is_empty() {
        out.push(InvariantViolation::here(format!(
            "Invariant Valid_value failed on type {ty} (value must be non-empty)"
        )));
    }
    if formatting.is_some_and(str::is_empty) {
        out.push(InvariantViolation::here(format!(
            "Invariant Formatting_valid failed on type {ty}"
        )));
    }
}

